async function testExecutor() {
  const lists = []
  const index = [
    { provider: 'claude', sessionId: UUID_A, cwd: 'c:\\repo', title: 'fix login', updatedAt: T0, lastMessage: '', messageCount: 2 },
    { provider: 'codex', sessionId: CODEX_X, cwd: 'C:\\Repo\\', title: 'codex', updatedAt: T0, lastMessage: '', messageCount: 2 },
    { provider: 'claude', sessionId: UUID_C, cwd: 'C:\\Repo', title: 'open one', updatedAt: T0, lastMessage: '', messageCount: 2 },
  ]
  const results = []
  const snApi = {
    platform: 'win32',
    sessions: { list: async (req) => { lists.push(req); return index.filter(s => s.sessionId.toLowerCase() === String(req.query).toLowerCase()) } },
    agents: { list: async () => [], startup: async () => ({ trigger: null, interrupted: [] }), consumeStartup: async () => true, startupPending: async () => [], forget() {}, onChanged: () => () => {}, onReady: () => () => {} },
    pty: { kill: async () => {}, killPanes: async () => 0 },
    config: { save() {} },
    window: { reveal() {} },
    remote: { onCommand: (cb) => { snApi._cmd = cb; return () => {} }, commandResult: (res) => results.push(res) },
  }
  const code = buildSync({ stdin: { contents: `export { useAppStore } from './store'; export { useAgentStore } from './agentStore'; export { prepareAgentLaunch } from './agentLaunch'; export { resolveLaunch } from './launch'; export { runCreatePaneResume, paneHoldingSession, resumePreset } from './remoteResume'; export { initRemoteCommands } from './remoteCommands'`, resolveDir: path.join(root, 'src/renderer/lib'), loader: 'ts' }, bundle: true, platform: 'node', format: 'cjs', write: false, alias, define: { 'process.env.NODE_ENV': '"production"' } }).outputFiles[0].text
  const mod = { exports: {} }
  vm.runInNewContext(code, { module: mod, exports: mod.exports, require, console, process, crypto: globalThis.crypto, setTimeout: () => 0, clearTimeout() {}, Promise, URL, window: { snApi }, document: { hasFocus: () => false, querySelector: () => null }, requestAnimationFrame: () => 0, cancelAnimationFrame() {} })
  const r = mod.exports
  const S = r.useAppStore, A = r.useAgentStore
  const claude = { id: 'preset-claude', name: 'Claude Code', type: 'claude', command: 'claude', args: ['--model', 'opus'], color: '#d97757', icon: 'claude' }
  const codex = { id: 'preset-codex', name: 'Codex', type: 'codex', command: 'codex', args: ['-m', 'o3'], color: '#10a37f', icon: 'openai' }
  S.getState().hydrate({
    version: 13,
    presets: [{ id: 'preset-shell', name: 'Shell', type: 'shell', command: '', args: [], color: '', icon: '' }, claude, codex],
    connections: [{ id: 'ssh', name: 'Server', steps: [{ kind: 'send', text: 'ssh me@host' }] }],
    settings: { ...S.getState().settings, notifications: { ...S.getState().settings.notifications, hooksEnabled: false } },
    activeWorkspaceId: 'w2',
    workspaces: [
      { id: 'w1', name: 'Ssh', cwd: '/srv', setupId: 'ssh', panes: [{ id: 'p1', type: 'claude', presetId: 'preset-claude', title: 'A', color: '', icon: '' }], layout: { grid: 1, order: ['p1'] } },
      { id: 'w2', name: 'Local', cwd: 'C:\\Repo', panes: [{ id: 'p2', type: 'claude', presetId: 'preset-claude', title: 'B', color: '', icon: '' }], layout: { grid: 1, order: ['p2'] } },
    ],
  })
  const paneOf = (id) => S.getState().workspaces.flatMap(w => w.panes).find(p => p.id === id)
  const wsOf = (id) => S.getState().workspaces.find(w => w.panes.some(p => p.id === id))
  const base = (id) => r.resolveLaunch(paneOf(id), wsOf(id), S.getState().presets, S.getState().connections)

  check(r.resumePreset([claude, codex], 'codex', 'preset-claude').id === 'preset-codex' && r.resumePreset([claude], 'claude', undefined).id === 'preset-claude' && r.resumePreset([claude], 'codex', undefined) === undefined, 'resume preset: the phone\'s when it is of that provider, else the first of the type, else none')

  // Claude in a workspace behind an SSH Connection Profile: the console runs local.
  let res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w1', paneType: 'claude', resume: { provider: 'claude', sessionId: UUID_A } })
  check(res.ok && res.paneId && JSON.stringify(lists.at(-1)) === JSON.stringify({ query: UUID_A }), 'the cwd is resolved through sessions:list({query: sessionId})')
  const p = paneOf(res.paneId)
  check(wsOf(res.paneId).id === 'w1' && p.cwd === 'c:\\repo' && p.setupId === '' && p.presetId === 'preset-claude' && p.command === undefined, 'the new console has the index cwd, setupId \'\' and the preset, and nothing in pane.command')
  check(p.lastSession && p.lastSession.provider === 'claude' && p.lastSession.sessionId === UUID_A && p.lastSession.cwd === 'c:\\repo', 'the console records lastSession')
  check(JSON.stringify(S.getState().mountedWorkspaces.w1) === JSON.stringify([res.paneId]) && S.getState().activeWorkspaceId === 'w2', 'only the new console is mounted; the desktop keeps its workspace')
  const b = base(res.paneId)
  check(!b.setup, 'setupId \'\' cancels the workspace\'s Connection Profile (the pane runs local)')
  let launch = await r.prepareAgentLaunch(res.paneId, b)
  check(launch.initialCommand === `claude --model opus --resume ${UUID_A}` && launch.cwd === 'c:\\repo' && launch.resumed === true && launch.launchKind === 'other', 'the first spawn runs buildAgentArgv\'s resume command in the session\'s folder: ' + launch.initialCommand)
  check(A.getState().resumeChip[res.paneId]?.kind === 'resumed', 'the console shows the resumed chip')
  launch = await r.prepareAgentLaunch(res.paneId, base(res.paneId))
  check(launch.initialCommand === 'claude --model opus' && !launch.resumed, 'a later spawn does not run --resume <id> as the console\'s own command')

  // The same session again: the console that holds it, no second console.
  const count = S.getState().workspaces.flatMap(w => w.panes).length
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w2', paneType: 'claude', resume: { provider: 'claude', sessionId: UUID_A.toUpperCase() } })
  check(res.ok && res.paneId === p.id && S.getState().workspaces.flatMap(w => w.panes).length === count, 'an open session acks ok with the existing paneId (lastSession), creating nothing')
  S.setState({ paneStatus: { ...S.getState().paneStatus, p2: { state: 'idle', precise: true, provider: 'claude', sessionId: UUID_C } } })
  const listsBefore = lists.length
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w1', resume: { provider: 'claude', sessionId: UUID_C } })
  check(res.ok && res.paneId === 'p2' && lists.length === listsBefore, 'a session live in a console (status sessionId) returns that console without even asking the index')

  // Codex keeps its preset args through buildAgentArgv.
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w2', paneType: 'codex', resume: { provider: 'codex', sessionId: CODEX_X } })
  const cp = paneOf(res.paneId)
  launch = await r.prepareAgentLaunch(res.paneId, base(res.paneId))
  check(cp.type === 'codex' && cp.presetId === 'preset-codex' && launch.initialCommand === `codex -m o3 resume ${CODEX_X}` && launch.cwd === 'C:\\Repo\\', 'Codex resumes with its preset args: ' + launch.initialCommand)

  // Without a preset of that provider: the bare binary.
  S.setState({ presets: S.getState().presets.filter(x => x.type !== 'codex') })
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w2', resume: { provider: 'codex', sessionId: CODEX_X } })
  check(res.ok && res.paneId === cp.id, 'the same Codex session goes to its console')
  S.setState({ workspaces: S.getState().workspaces.map(w => ({ ...w, panes: w.panes.filter(x => x.id !== cp.id) })) })
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w2', resume: { provider: 'codex', sessionId: CODEX_X } })
  const bare = paneOf(res.paneId)
  launch = await r.prepareAgentLaunch(res.paneId, base(res.paneId))
  check(bare.presetId === undefined && bare.title === 'Codex' && launch.initialCommand === `codex resume ${CODEX_X}`, 'no Codex preset: the bare binary resumes')

  // Gone from the index between main's check and the executor: notFound, no console.
  const n = S.getState().workspaces.flatMap(w => w.panes).length
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'w2', resume: { provider: 'claude', sessionId: UUID_B } })
  check(!res.ok && res.error === 'notFound' && S.getState().workspaces.flatMap(w => w.panes).length === n, 'a session missing from sessions:list acks notFound and creates nothing')
  res = await r.runCreatePaneResume({ kind: 'createPane', workspaceId: 'gone', resume: { provider: 'claude', sessionId: UUID_A } })
  check(!res.ok && res.error === 'not_found', 'an unknown workspace is not_found')

  // Through the control-command stream: the resume branch of the createPane case.
  r.initRemoteCommands()
  index.push({ provider: 'claude', sessionId: UUID_E, cwd: 'C:\\Other', title: 'other', updatedAt: T0, lastMessage: '', messageCount: 1 })
  snApi._cmd({ id: 'k1', action: { kind: 'createPane', workspaceId: 'w2', paneType: 'claude', resume: { provider: 'claude', sessionId: UUID_E } } })
  await tick(); await tick()
  const out = results.find(x => x.id === 'k1')
  check(out && out.ok && paneOf(out.paneId)?.cwd === 'C:\\Other', 'the remote createPane with resume runs the resume branch and reports the new paneId')
}

