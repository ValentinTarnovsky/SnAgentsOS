async function remoteWorld() {
  const code = (await build({ stdin: { resolveDir: root, loader: 'ts', contents: `export { RemoteManager } from './src/main/remote/RemoteManager'` }, bundle: true, platform: 'node', format: 'cjs', write: false, external: ['electron', 'ws', 'qrcode'], plugins: [stubs], alias })).outputFiles[0].text
  const ctx = { module: { exports: {} }, require: id => id === 'qrcode' ? { toDataURL: async () => 'data:' } : require(id), console, process, Buffer, URL, queueMicrotask, setTimeout, clearTimeout, setInterval: () => 0, clearInterval() {}, Date }
  ctx.exports = ctx.module.exports
  ctx.globalThis = ctx
  vm.runInNewContext(code, ctx)
  const commands = []
  const pty = { addSink() {}, removeSink() {}, setRunningChangeListener() {}, setForcedFast() {}, runningPaneIds: () => [], exitedPaneCodes: () => new Map(), getReplay: () => null, getExited: () => null, ptyIdForPane: () => null, write() {} }
  const wc = { isDestroyed: () => false, setBackgroundThrottling() {}, send: (ch, cmd) => { if (ch === 'remote:controlCmd') commands.push(cmd) } }
  const manager = new ctx.module.exports.RemoteManager(pty, () => wc, '2.0.0', () => [], () => 'PC')
  manager.applyConfig({ enabled: true, port: 4601 })
  await tick()
  class FakeSocket {
    constructor() { this.readyState = 1; this.bufferedAmount = 0; this.inbox = []; this.handlers = {}; this.closed = null }
    on(ev, fn) { this.handlers[ev] = fn }
    send(data) { this.inbox.push(JSON.parse(data)) }
    close(code) { this.closed = code; this.readyState = 3; this.handlers.close && this.handlers.close() }
    terminate() { this.close(1006) }
    msg(obj) { this.handlers.message(JSON.stringify({ v: 1, ...obj })) }
    of(type) { return this.inbox.filter(m => m.type === type) }
  }
  const payload = await manager.pairingBegin()
  const ws = new FakeSocket()
  ctx.__server.handlers.onSocket(ws, '100.64.0.9', '100.64.0.9')
  ws.msg({ type: 'hello', clientNonce: 'aa'.repeat(32) })
  ws.msg({ type: 'pair', code: payload.code, deviceName: 'Phone' })
  manager.pairingResolve(manager.getUiState().pendingPairing.requestId, true)
  return { manager, ws, commands }
}

async function testRemote() {
  const { manager, ws, commands } = await remoteWorld()
  check(ws.of('authOk').length === 1, 'the phone is paired')
  ws.msg({ type: 'historyReq', id: 'h0' })
  await tick()
  const empty = ws.of('historyRes').find(m => m.id === 'h0')
  check(empty && Array.isArray(empty.sessions) && empty.sessions.length === 0, 'without a history index the phone still gets an (empty) answer')

  const asked = []
  const sessions = Array.from({ length: 150 }, (_, i) => ({ provider: 'claude', sessionId: crypto.randomUUID(), cwd: 'C:\\Repo', title: 'session ' + i, updatedAt: 1000 - i }))
  manager.setHistory({
    forRemote: async (req) => { asked.push(req); return sessions },
    has: async (provider, id) => provider === 'claude' && id === UUID_A,
  })
  ws.msg({ type: 'historyReq', id: 'h1', query: 'login', workspaceId: 'w1' })
  await tick()
  const res = ws.of('historyRes').find(m => m.id === 'h1')
  check(JSON.stringify(asked[0]) === JSON.stringify({ query: 'login', workspaceId: 'w1' }), 'historyReq reaches SessionHistory with its query and workspace')
  check(res && res.sessions.length === 100 && res.sessions[0].title === 'session 0' && Buffer.byteLength(JSON.stringify(res)) <= 49152, 'historyRes carries the 100 most recent, under 48KB')
  ws.msg({ type: 'historyReq', id: 'h2', query: 'q'.repeat(201) })
  check(ws.of('err').some(m => m.code === 'bad_msg'), 'a query over 200 characters is a malformed frame')

  const before = commands.length
  ws.msg({ type: 'ctl', id: 'c1', action: { kind: 'createPane', workspaceId: 'w1', paneType: 'claude', resume: { provider: 'claude', sessionId: 'x; rm -rf /' } } })
  await tick()
  let ack = ws.of('ctlAck').find(a => a.id === 'c1')
  check(ack && !ack.ok && ack.error === 'notFound' && commands.length === before, 'a session id outside ^[0-9a-fA-F-]{8,64}$ acks notFound and nothing reaches the renderer')
  ws.msg({ type: 'ctl', id: 'c2', action: { kind: 'createPane', workspaceId: 'w1', paneType: 'claude', resume: { provider: 'claude', sessionId: UUID_B } } })
  await tick()
  ack = ws.of('ctlAck').find(a => a.id === 'c2')
  check(ack && ack.error === 'notFound' && commands.length === before, 'an id that is not in the index acks notFound without relaying')
  ws.msg({ type: 'ctl', id: 'c3', action: { kind: 'createPane', workspaceId: 'w1', paneType: 'claude', resume: { provider: 'codex', sessionId: UUID_A } } })
  await tick()
  check(ws.of('ctlAck').find(a => a.id === 'c3')?.error === 'notFound', 'the provider has to match the indexed session')
  ws.msg({ type: 'ctl', id: 'c4', action: { kind: 'createPane', workspaceId: 'w1', paneType: 'claude', resume: { provider: 'claude', sessionId: UUID_A } } })
  await tick()
  const relayed = commands.at(-1)
  check(commands.length === before + 1 && relayed.action.resume.sessionId === UUID_A && !('cwd' in relayed.action), 'an indexed session is relayed to the renderer, with no cwd from the phone')
  manager.onControlResult({ id: relayed.id, ok: true, paneId: 'new-pane' })
  await tick()
  ack = ws.of('ctlAck').find(a => a.id === 'c4')
  check(ack && ack.ok && ack.paneId === 'new-pane', 'the phone gets ctlAck {ok, paneId}')
  ws.msg({ type: 'ctl', id: 'c5', action: { kind: 'createPane', workspaceId: 'w1', presetId: 'preset-claude' } })
  check(commands.length === before + 2, 'a createPane without resume is relayed at once, as before')
  ws.msg({ type: 'ctl', id: 'c6', action: { kind: 'createPane', workspaceId: 'w1', resume: { provider: 'gemini', sessionId: UUID_A } } })
  check(ws.of('err').filter(m => m.code === 'bad_msg').length === 2, 'an unknown provider is a malformed frame')
  manager.shutdown('quit')
}

