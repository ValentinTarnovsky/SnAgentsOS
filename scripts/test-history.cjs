async function testIndex() {
  seedTrees()
  const H = loadMain(`export * from './src/main/history/SessionHistory'`)
  let statuses = []
  const timers = []
  const history = new H.SessionHistory({
    claudeProjectsDir: () => claudeRoot,
    codexSessionsRoot: () => codexRoot,
    getConfig: () => config,
    openSessions: () => H.openSessionsOf(statuses, config),
    platform: 'win32',
    forcedRescanMs: 0,
    setTimer: (fn, ms) => { timers.push({ fn, ms }); return timers.length },
    clearTimer() {},
  })

  // --- Pure helpers ---
  check(H.normalizeCwd('C:\\Repo\\', 'win32') === H.normalizeCwd('c:\\repo', 'win32') && H.normalizeCwd('C:\\', 'win32') === 'c:\\', 'cwd matching ignores case and a trailing separator on win32 (a drive root keeps its own)')
  check(H.normalizeCwd('/srv/app/', 'linux') === '/srv/app' && H.normalizeCwd('/Srv', 'linux') !== H.normalizeCwd('/srv', 'linux'), 'POSIX keeps case and drops the trailing separator')
  const scope = H.workspaceCwds(config, 'w2', 'win32')
  check(JSON.stringify([...scope].sort()) === JSON.stringify(['c:\\pane', 'c:\\preset', 'c:\\ws', 'd:\\own']), 'workspace scope: ws.cwd plus pane.cwd > preset.defaultCwd > ws.cwd per console: ' + [...scope])
  check(H.workspaceCwds(config, 'gone', 'win32').size === 0, 'an unknown workspace has no directories')
  check(H.sessionTitle({ customTitle: 'T', summary: 'S', firstPrompt: 'P' }) === 'T' && H.sessionTitle({ summary: 'S', firstPrompt: 'P' }) === 'S' && H.sessionTitle({ firstPrompt: 'a\n\tb' }) === 'a b', 'title precedence: custom > summary > first prompt (one line)')
  check(H.isUsableCwd('C:\\x') && H.isUsableCwd('/x') && H.isUsableCwd('\\\\srv\\share') && !H.isUsableCwd('relative') && !H.isUsableCwd('C:\\a\nb') && !H.isUsableCwd(''), 'only absolute, single-line cwds are kept')

  // --- Listing ---
  const all = await history.list()
  const ids = all.map(s => s.sessionId)
  check(!ids.includes(UUID_D) && !ids.includes(CODEX_Z), 'empty sessions (only slash commands, caveats or no prompt) are not listed')
  check(!ids.some(id => /agent/.test(id)) && all.length === 8, 'subagent transcripts and nested folders are skipped: ' + ids.length)
  check(ids[0] === CODEX_Y && ids[1] === CODEX_X && all.every((s, i) => i === 0 || all[i - 1].updatedAt >= s.updatedAt), 'newest first (by the last record\'s time)')
  const byId = Object.fromEntries(all.map(s => [s.sessionId, s]))
  check(byId[UUID_A].title === 'fix the login bug please' && byId[UUID_A].lastMessage === 'Done, the login works now' && byId[UUID_A].cwd === 'c:\\repo', 'title from the first prompt, last message from the reply, cwd as recorded')
  check(byId[UUID_B].title === 'Refactor of the payments module', 'the summary wins over the first prompt')
  check(byId[UUID_C].title === 'My named session', 'the custom title wins over the summary')
  check(byId[UUID_H].title.length <= 60 && byId[UUID_H].title === 'word '.repeat(12).trim(), 'the first prompt is cut to 60 characters: ' + JSON.stringify(byId[UUID_H].title))
  check(!JSON.stringify(all).includes('secret output'), 'tool results never become a title or a message')
  check(byId[UUID_F].title === 'big session start' && byId[UUID_F].lastMessage === 'final answer xyz' && byId[UUID_F].updatedAt === T0 + 9500, 'a file past 128KB: title from the first 64KB, last message and date from the last 64KB')
  check(byId[CODEX_X].title === 'codex prompt about login' && byId[CODEX_X].lastMessage === 'codex reply' && byId[CODEX_X].provider === 'codex', 'Codex: the environment block is not a prompt; title and reply from event_msg')
  check(all.every(s => s.messageCount === null), 'message counts are unknown until the background job reaches them')

  // --- Query and scope ---
  const login = await history.list({ query: 'LOGIN' })
  check(JSON.stringify(login.map(s => s.sessionId).sort()) === JSON.stringify([UUID_A, CODEX_X].sort()), 'query matches the title and the last message, case-insensitive')
  check((await history.list({ query: 'works now' }))[0]?.sessionId === UUID_A, 'query matches the last message alone')
  const exact = await history.list({ query: UUID_B.toUpperCase() })
  check(exact.length === 1 && exact[0].sessionId === UUID_B, 'sessions:list with an exact session id returns that session')
  check((await history.list({ cwd: 'C:\\REPO\\' })).length === 6, 'sessions:list filters by cwd case- and separator-insensitively')
  const ws1 = await history.forRemote({ workspaceId: 'w1' })
  check(ws1.some(s => s.sessionId === UUID_A) && ws1.some(s => s.sessionId === UUID_C), '"This workspace" includes C:\\Repo\\ sessions registered as c:\\repo')
  check(!ws1.some(s => s.sessionId === UUID_E) && !ws1.some(s => s.sessionId === CODEX_Y), 'sessions of another cwd (Claude or Codex session_meta) stay out of "This workspace"')
  check(ws1.some(s => s.sessionId === CODEX_X), 'a Codex rollout whose session_meta cwd is the workspace\'s is in')
  check((await history.forRemote({})).length === 8 && (await history.forRemote({ workspaceId: 'gone' })).length === 0, '"All projects" lists everything; an unknown workspace lists nothing')
  check(Object.keys(ws1[0]).every(k => ['provider', 'sessionId', 'cwd', 'title', 'updatedAt', 'paneId'].includes(k)), 'historyRes items carry only the contract fields (lastMessage stays desktop-side)')

  // --- Open sessions (E3-FR-38) ---
  statuses = [{ paneId: 'p1', state: 'idle', precise: true, notify: false, provider: 'claude', sessionId: UUID_A }, { paneId: 'ghost', state: 'idle', precise: true, notify: false, provider: 'claude', sessionId: UUID_C }]
  const marked = await history.forRemote({})
  const mk = Object.fromEntries(marked.map(s => [s.sessionId, s.paneId]))
  check(mk[UUID_A] === 'p1' && mk[UUID_B] === 'q4' && !mk[UUID_C] && !mk[UUID_E], 'a session open in a console (live status or lastSession) carries its paneId; a status of a deleted pane does not')

  // --- has() (createPane.resume check) ---
  check(await history.has('claude', UUID_A) && await history.has('codex', CODEX_X), 'indexed sessions are found')
  check(!(await history.has('codex', UUID_A)) && !(await history.has('claude', 'not-a-session!')) && !(await history.has('claude', 'ffffffff-0000')), 'wrong provider, bad format or unknown id: not found')
  const NEW = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee'
  writeJsonl(claudeFile('C--Repo', NEW), [user('started a moment ago', 'C:\\Repo', T0 + 20000)], T0 + 20000)
  check(await history.has('claude', NEW), 'a session written after the last scan is found by the rescan on a miss')

  // --- Background count ---
  check(timers.length > 0 && timers[0].ms === 50, 'the background count runs one file every 50ms')
  let n = 0
  while (await history.countNext()) n++
  const counted = Object.fromEntries((await history.list()).map(s => [s.sessionId, s.messageCount]))
  check(n === 9 && counted[UUID_A] === 2 && counted[UUID_F] === 402 && counted[UUID_H] === 2 && counted[CODEX_X] === 2, 'exact counts: prompts and replies only, no sidechain, tool result or context block: ' + JSON.stringify(counted))
  fs.appendFileSync(claudeFile('C--Repo', UUID_A), JSON.stringify(reply('one more', T0 + 30000)) + '\n')
  fs.utimesSync(claudeFile('C--Repo', UUID_A), new Date(T0 + 30000), new Date(T0 + 30000))
  await history.refresh(true)
  const after = (await history.list({ query: UUID_A }))[0]
  check(after.messageCount === null && after.lastMessage === 'one more' && after.updatedAt === T0 + 30000, 'a changed file (mtime, size) is read again and recounted')
  while (await history.countNext()) { /* the grown file only */ }
  check((await history.list({ query: UUID_A }))[0].messageCount === 3, 'the grown file is recounted to the exact total')

  // Incremental count: a grown file resumes from the last complete line, and
  // an unterminated last line is counted now and read again once complete.
  const inc = path.join(tmp, 'count', 'inc.jsonl')
  writeJsonl(inc, [user('one', 'C:\\x', T0), reply('two', T0 + 1)])
  const first = await H.countMessagesFrom(inc, 'claude')
  check(first.count === 2 && first.progress.offset === fs.statSync(inc).size && first.progress.count === 2, 'a count stops after the last complete line: ' + JSON.stringify(first))
  const partial = JSON.stringify(reply('three', T0 + 2))
  fs.appendFileSync(inc, partial.slice(0, 20))
  const mid = await H.countMessagesFrom(inc, 'claude', first.progress)
  check(mid.count === 2 && mid.progress.offset === first.progress.offset, 'a half-written last line is not counted and not skipped')
  fs.appendFileSync(inc, partial.slice(20))
  const unterminated = await H.countMessagesFrom(inc, 'claude', mid.progress)
  check(unterminated.count === 3 && unterminated.progress.count === 2, 'a complete but unterminated last line counts without moving the resume point')
  fs.appendFileSync(inc, '\n' + JSON.stringify(user('ü four €', 'C:\\x', T0 + 3)) + '\n')
  const grown = await H.countMessagesFrom(inc, 'claude', unterminated.progress)
  check(grown.count === 4 && grown.count === (await H.countMessages(inc, 'claude')) && grown.progress.offset === fs.statSync(inc).size, 'resuming gives the same total as a full count: ' + JSON.stringify(grown))
  // From an offset past every record the old lines are never read again.
  const skip = await H.countMessagesFrom(inc, 'claude', { offset: fs.statSync(inc).size, count: 7 })
  check(skip.count === 7, 'a count from the end reads nothing before it')
  history.dispose()
  return H
}

async function testScale(H) {
  // 300 sessions: the search answers well within 500ms on a warm index.
  const big = path.join(tmp, 'scale', 'projects')
  for (let i = 0; i < 300; i++) {
    const id = crypto.randomUUID()
    const title = i % 10 === 0 ? `fix login flow ${i}` : `task number ${i} ` + 'x'.repeat(100)
    writeJsonl(path.join(big, 'C--Repo', id + '.jsonl'), [user(title, 'C:\\' + 'deep\\'.repeat(40) + 'Repo', T0 + i), reply('reply ' + i, T0 + i + 1)], T0 + i)
  }
  const history = new H.SessionHistory({ claudeProjectsDir: () => big, codexSessionsRoot: () => path.join(tmp, 'none'), getConfig: () => config, platform: 'win32', setTimer: () => 0 })
  let t = Date.now()
  const cold = await history.forRemote({})
  const coldMs = Date.now() - t
  t = Date.now()
  const hits = await history.forRemote({ query: 'login' })
  const warmMs = Date.now() - t
  check(cold.length === 300 && hits.length === 30 && warmMs < 500, `300 sessions: "login" filters in ${warmMs}ms warm (${coldMs}ms cold)`)
  history.dispose()

  const SM = loadMain(`export { fitHistoryRes, HISTORY_RES_MAX, REMOTE_FRAME_MAX_BYTES } from './src/main/remote/SessionManager'`)
  const frame = SM.fitHistoryRes('h1', cold)
  const bytes = Buffer.byteLength(JSON.stringify(frame))
  check(frame.sessions.length <= 100 && bytes <= 49152 && frame.sessions.length > 0, `historyRes of 300 long sessions: ${frame.sessions.length} sessions in ${bytes} bytes (<= 48KB)`)
  check(frame.sessions[0].sessionId === cold[0].sessionId, 'the trim drops the oldest, never the newest')
  const small = SM.fitHistoryRes('h2', cold.map(s => ({ ...s, cwd: 'C:\\r', title: 't' })))
  check(small.sessions.length === 100, 'small sessions: exactly the 100 most recent')
  const huge = SM.fitHistoryRes('h3', [{ provider: 'claude', sessionId: UUID_A, cwd: 'C:\\' + 'z'.repeat(60000), title: 't', updatedAt: 1 }])
  check(huge.sessions.length === 0 && Buffer.byteLength(JSON.stringify(huge)) <= 49152, 'a single session over 48KB is dropped rather than overflow the frame')
}

